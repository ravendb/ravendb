using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Raven.Server.SourceGenerators
{
    /// <summary>
    /// Builds the route table of Raven.Server at compile time, one static method per [RavenAction] / [RavenShardedAction] method,
    /// so the server doesn't scan all its types and compile an expression tree per route when it starts.
    /// </summary>
    [Generator]
    public sealed class RouteTableGenerator : IIncrementalGenerator
    {
        private const string ActionAttribute = "Raven.Server.Routing.RavenActionAttribute";
        private const string ShardedActionAttribute = "Raven.Server.Routing.RavenShardedActionAttribute";
        private const string DatabaseRequestHandler = "Raven.Server.Documents.DatabaseRequestHandler";

        private static readonly DiagnosticDescriptor InvalidAction = new(
            id: "RVNROUTE001",
            title: "Invalid route action",
            messageFormat: "'{0}' cannot handle a route: {1}",
            category: "Raven.Routing",
            DiagnosticSeverity.Error,
            isEnabledByDefault: true);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var actions = context.SyntaxProvider.ForAttributeWithMetadataName(ActionAttribute,
                static (node, _) => node is MethodDeclarationSyntax,
                static (ctx, _) => Action.Create(ctx));

            var shardedActions = context.SyntaxProvider.ForAttributeWithMetadataName(ShardedActionAttribute,
                static (node, _) => node is MethodDeclarationSyntax,
                static (ctx, _) => Action.Create(ctx));

            context.RegisterSourceOutput(actions.Collect().Combine(shardedActions.Collect()),
                static (spc, all) => Emit(spc, all.Left, all.Right));
        }

        private static void Emit(SourceProductionContext context, ImmutableArray<Action> actions, ImmutableArray<Action> shardedActions)
        {
            var valid = true;
            foreach (var action in actions.Concat(shardedActions))
            {
                if (action.Error == null)
                    continue;

                context.ReportDiagnostic(Diagnostic.Create(InvalidAction, action.Location, action.Name, action.Error));
                valid = false;
            }

            if (valid == false)
                return;

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable disable");
            sb.AppendLine();
            sb.AppendLine("namespace Raven.Server.Routing");
            sb.AppendLine("{");
            sb.AppendLine("    internal static partial class RouteTable");
            sb.AppendLine("    {");

            // sorted, so the output doesn't depend on the order the compiler visits the files
            var ordered = actions.OrderBy(x => x.Name, System.StringComparer.Ordinal).ToArray();
            var orderedSharded = shardedActions.OrderBy(x => x.Name, System.StringComparer.Ordinal).ToArray();

            sb.AppendLine("        internal static readonly GeneratedRoute[] Actions =");
            sb.AppendLine("        [");
            for (var i = 0; i < ordered.Length; i++)
            {
                foreach (var attribute in ordered[i].Attributes)
                    sb.AppendLine($"            new GeneratedRoute(\"{ordered[i].Name}\", isDatabaseHandler: {(ordered[i].IsDatabaseHandler ? "true" : "false")}, Action{i}, {attribute}),");
            }
            sb.AppendLine("        ];");
            sb.AppendLine();

            sb.AppendLine("        internal static readonly GeneratedShardedRoute[] ShardedActions =");
            sb.AppendLine("        [");
            for (var i = 0; i < orderedSharded.Length; i++)
            {
                foreach (var attribute in orderedSharded[i].Attributes)
                    sb.AppendLine($"            new GeneratedShardedRoute(\"{orderedSharded[i].Name}\", ShardedAction{i}, {attribute}),");
            }
            sb.AppendLine("        ];");

            for (var i = 0; i < ordered.Length; i++)
                AppendHandler(sb, "Action" + i, ordered[i]);

            for (var i = 0; i < orderedSharded.Length; i++)
                AppendHandler(sb, "ShardedAction" + i, orderedSharded[i]);

            sb.AppendLine("    }");
            sb.AppendLine("}");

            context.AddSource("RouteTable.g.cs", sb.ToString());
        }

        private static void AppendHandler(StringBuilder sb, string name, Action action)
        {
            sb.AppendLine();
            sb.AppendLine($"        private static global::System.Threading.Tasks.Task {name}(global::Raven.Server.Web.RequestHandlerContext context)");
            sb.AppendLine("        {");
            sb.AppendLine($"            var handler = new {action.HandlerType}();");
            sb.AppendLine("            handler.Init(context);");
            sb.AppendLine($"            return handler.{action.MethodName}();");
            sb.AppendLine("        }");
        }

        private sealed record Action(string Name, string HandlerType, string MethodName, bool IsDatabaseHandler, EquatableArray Attributes, string Error, Location Location)
        {
            public static Action Create(GeneratorAttributeSyntaxContext context)
            {
                var method = (IMethodSymbol)context.TargetSymbol;
                var type = method.ContainingType;
                var name = type.ToDisplayString() + "." + method.Name;
                var attributes = new EquatableArray(context.Attributes.Select(ToCreationExpression).ToArray());
                var isDatabaseHandler = InheritsFrom(type, DatabaseRequestHandler);

                return new Action(name, type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat), method.Name, isDatabaseHandler, attributes,
                    Validate(method), method.Locations.FirstOrDefault());
            }

            private static string Validate(IMethodSymbol method)
            {
                var type = method.ContainingType;

                if (method.IsStatic || method.DeclaredAccessibility != Accessibility.Public)
                    return "it must be a public instance method";
                if (method.Parameters.Length != 0 || method.IsGenericMethod)
                    return "it must not have parameters";
                if (method.ReturnType.ToDisplayString() != "System.Threading.Tasks.Task")
                    return "it must return Task";
                if (type.IsAbstract || type.IsGenericType)
                    return "its type must be a non generic, non abstract class";
                if (type.InstanceConstructors.Any(c => c.Parameters.Length == 0 && c.DeclaredAccessibility == Accessibility.Public) == false)
                    return "its type must have a public parameterless constructor";

                for (var t = type; t != null; t = t.ContainingType)
                {
                    if (t.DeclaredAccessibility is not (Accessibility.Public or Accessibility.Internal))
                        return "its type must be accessible from the generated route table";
                }

                return null;
            }

            private static bool InheritsFrom(INamedTypeSymbol type, string baseType)
            {
                for (var t = type; t != null; t = t.BaseType)
                {
                    if (t.ToDisplayString() == baseType)
                        return true;
                }

                return false;
            }

            private static string ToCreationExpression(AttributeData attribute)
            {
                var sb = new StringBuilder("new ")
                    .Append(attribute.AttributeClass.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                    .Append('(')
                    .Append(string.Join(", ", attribute.ConstructorArguments.Select(ToCSharp)))
                    .Append(')');

                if (attribute.NamedArguments.Length > 0)
                {
                    sb.Append(" { ")
                        .Append(string.Join(", ", attribute.NamedArguments.Select(x => x.Key + " = " + ToCSharp(x.Value))))
                        .Append(" }");
                }

                return sb.ToString();
            }

            private static string ToCSharp(TypedConstant value)
            {
                if (value.Kind != TypedConstantKind.Enum)
                    return value.ToCSharpString();

                var enumType = value.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                var member = value.Type.GetMembers().OfType<IFieldSymbol>().FirstOrDefault(f => f.HasConstantValue && Equals(f.ConstantValue, value.Value));
                return member != null ? enumType + "." + member.Name : "(" + enumType + ")" + value.Value;
            }
        }

        /// <summary>
        /// An array with value equality, so the incremental pipeline can tell when nothing changed.
        /// </summary>
        private sealed class EquatableArray(string[] items) : System.IEquatable<EquatableArray>, System.Collections.Generic.IEnumerable<string>
        {
            private readonly string[] _items = items;

            public bool Equals(EquatableArray other) => other != null && _items.SequenceEqual(other._items);

            public override bool Equals(object obj) => Equals(obj as EquatableArray);

            public override int GetHashCode() => _items.Aggregate(17, (hash, item) => hash * 31 + item.GetHashCode());

            public System.Collections.Generic.IEnumerator<string> GetEnumerator() => ((System.Collections.Generic.IEnumerable<string>)_items).GetEnumerator();

            System.Collections.IEnumerator System.Collections.IEnumerable.GetEnumerator() => GetEnumerator();
        }
    }
}
