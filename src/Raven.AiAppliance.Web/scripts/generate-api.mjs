import { execFileSync } from "node:child_process";
import { readFileSync, rmSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const httpMethods = ["get", "post", "put", "patch", "delete", "head", "options"];
const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const webDirectory = path.resolve(scriptDirectory, "..");
const repoRoot = path.resolve(webDirectory, "..", "..");
const backendProject = path.resolve(repoRoot, "src", "Raven.AiAppliance", "Raven.AiAppliance.csproj");
const specPath = process.env.RAVEN_AI_OPENAPI_SPEC_PATH
    ? path.resolve(webDirectory, process.env.RAVEN_AI_OPENAPI_SPEC_PATH)
    : path.resolve(repoRoot, "src", "Raven.AiAppliance", "obj", "openapi", "ai-appliance.json");
const outputPath = path.resolve(webDirectory, "src", "api", "generated", "server-api.ts");
const openApiTypescriptCliPath = path.resolve(webDirectory, "node_modules", "openapi-typescript", "bin", "cli.js");
const tempSpecPath = path.join(os.tmpdir(), `raven-ai-appliance-openapi-${process.pid}.json`);
const tempTypesPath = path.join(os.tmpdir(), `raven-ai-appliance-openapi-${process.pid}.ts`);

try {
    if (process.env.RAVEN_AI_OPENAPI_SKIP_SPEC_BUILD !== "1") {
        run("dotnet", ["build", backendProject, "--nologo", "--tl:off"], repoRoot);
    }

    if (!existsSync(specPath)) {
        throw new Error(`OpenAPI document not found at ${specPath}`);
    }

    const spec = JSON.parse(readFileSync(specPath, "utf8"));
    normalizeOpenApiNumericTypes(spec);
    writeFileSync(tempSpecPath, JSON.stringify(spec));

    run(process.execPath, [openApiTypescriptCliPath, tempSpecPath, "-o", tempTypesPath], webDirectory);

    const operations = collectOperations(spec.paths ?? {});
    const generatedTypes = stripOpenApiTypesBanner(readFileSync(tempTypesPath, "utf8").trim());
    const schemaAliases = buildSchemaAliases(spec.components?.schemas ?? {});
    const endpointHelpers = buildEndpointHelpers(operations);
    const generatedClient = buildGeneratedClient(operations);
    const output = [
        "// This file is auto-generated by src/Raven.AiAppliance.Web/scripts/generate-api.mjs.",
        "// Do not edit by hand.",
        "",
        'import type { ApiClient } from "@/api/http-client";',
        "",
        generatedTypes,
        "",
        schemaAliases,
        "",
        endpointHelpers,
        "",
        generatedClient,
        "",
    ].join("\n");

    mkdirSync(path.dirname(outputPath), { recursive: true });

    if (!existsSync(outputPath) || readFileSync(outputPath, "utf8") !== output) {
        writeFileSync(outputPath, output);
    }

    console.log(`Generated ${path.relative(webDirectory, outputPath)}`);
} finally {
    rmSync(tempSpecPath, { force: true });
    rmSync(tempTypesPath, { force: true });
}

function buildSchemaAliases(schemas) {
    const names = Object.keys(schemas).sort((left, right) => left.localeCompare(right));
    if (names.length === 0) {
        return "";
    }

    const lines = [];
    for (const name of names) {
        if (!isValidIdentifier(name)) {
            throw new Error(`Schema name '${name}' is not a valid TypeScript identifier.`);
        }

        lines.push(`export type ${name} = components[\"schemas\"][\"${name}\"];`);
    }

    return lines.join("\n");
}

function buildEndpointHelpers(operations) {
    const groupedOperations = groupOperations(operations);
    const lines = ["export const API_ENDPOINTS = {"];
    for (const groupName of [...groupedOperations.keys()].sort((left, right) => left.localeCompare(right))) {
        lines.push(`    ${groupName}: {`);
        const group = groupedOperations.get(groupName);

        for (const helperName of [...group.keys()].sort((left, right) => left.localeCompare(right))) {
            const operation = group.get(helperName);
            if (operation.pathParameters.length === 0) {
                lines.push(`        ${helperName}: \"${operation.routePath}\",`);
                continue;
            }

            const signature = operation.pathParameters
                .map((parameter) => `${parameter.name}: ${parameter.type}`)
                .join(", ");
            let template = operation.routePath;
            for (const parameter of operation.pathParameters) {
                template = template.replace(
                    `{${parameter.name}}`,
                    "${encodeURIComponent(" + parameter.name + ")}",
                );
            }

            lines.push(`        ${helperName}: (${signature}) => \`${template}\`,`);
        }

        lines.push("    },");
    }

    lines.push("} as const;");
    return lines.join("\n");
}

function buildGeneratedClient(operations) {
    const groupedOperations = groupOperations(operations);

    const lines = ["export function createServerApi(client: ApiClient) {", "    return {"];
    for (const groupName of [...groupedOperations.keys()].sort((left, right) => left.localeCompare(right))) {
        lines.push(`        ${groupName}: {`);
        const group = groupedOperations.get(groupName);

        for (const helperName of [...group.keys()].sort((left, right) => left.localeCompare(right))) {
            const operation = group.get(helperName);
            const args = [];
            const pathArgumentList = operation.pathParameters.map((parameter) => parameter.name).join(", ");

            for (const parameter of operation.pathParameters) {
                args.push(`${parameter.name}: ${parameter.type}`);
            }

            if (operation.requestBodyType) {
                args.push(`request: ${operation.requestBodyType}`);
            }

            if (operation.queryParameters.length > 0) {
                args.push(`searchParams${operation.hasRequiredQueryParameters ? "" : "?"}: ${buildQueryParameterType(operation.queryParameters)}`);
            }

            const endpointExpression = operation.pathParameters.length === 0
                ? `API_ENDPOINTS.${groupName}.${helperName}`
                : `API_ENDPOINTS.${groupName}.${helperName}(${pathArgumentList})`;
            const clientArguments = [endpointExpression];

            if (operation.requestBodyType) {
                clientArguments.push("request");
                if (operation.queryParameters.length > 0) {
                    clientArguments.push(operation.responseTypeOption
                        ? `{ searchParams, responseType: "${operation.responseTypeOption}" }`
                        : "{ searchParams }");
                } else if (operation.responseTypeOption) {
                    clientArguments.push(`{ responseType: "${operation.responseTypeOption}" }`);
                }
            } else if (operation.queryParameters.length > 0) {
                clientArguments.push(operation.responseTypeOption
                    ? `{ searchParams, responseType: "${operation.responseTypeOption}" }`
                    : "{ searchParams }");
            } else if (operation.responseTypeOption) {
                clientArguments.push(`{ responseType: "${operation.responseTypeOption}" }`);
            }

            const typeArguments = operation.errorType === "unknown"
                ? operation.responseType
                : `${operation.responseType}, ${operation.errorType}`;

            lines.push(
                `            ${helperName}: (${args.join(", ")}) => client.${operation.method}<${typeArguments}>(${clientArguments.join(", ")}),`,
            );
        }

        lines.push("        },");
    }

    lines.push("    };", "}", "", "export type ServerApi = ReturnType<typeof createServerApi>;");
    return lines.join("\n");
}

function toTypeScriptType(schema) {
    if (!schema) {
        return "string";
    }

    if (schema.$ref) {
        const [, , kind, name] = schema.$ref.split("/");
        if (kind === "schemas" && name && isValidIdentifier(name)) {
            return name;
        }

        throw new Error(`Unsupported schema reference '${schema.$ref}'.`);
    }

    if (Array.isArray(schema.enum) && schema.enum.length > 0) {
        return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
    }

    if (schema.type === "array") {
        return `${toTypeScriptType(schema.items)}[]`;
    }

    switch (schema.type) {
        case "integer":
        case "number":
            return "number";
        case "boolean":
            return "boolean";
        default:
            return "string";
    }
}

function normalizeRoutePath(routePath) {
    let normalized = routePath.startsWith("/api/") ? routePath.slice(4) : routePath;
    if (normalized.length > 1 && normalized.endsWith("/")) {
        normalized = normalized.slice(0, -1);
    }

    return normalized;
}

function collectOperations(paths) {
    const operations = [];

    for (const routePath of Object.keys(paths).sort((left, right) => left.localeCompare(right))) {
        const pathItem = paths[routePath] ?? {};
        for (const method of httpMethods) {
            const operation = pathItem[method];
            if (!operation) {
                continue;
            }

            const operationId = operation.operationId;
            if (!operationId) {
                throw new Error(`Missing operationId for ${method.toUpperCase()} ${routePath}`);
            }

            const [groupName, helperName, ...rest] = operationId.split(".");
            if (!groupName || !helperName || rest.length > 0) {
                throw new Error(`OperationId '${operationId}' must match '<group>.<name>'.`);
            }

            const { pathParameters, queryParameters } = resolveParameters(routePath, pathItem.parameters, operation.parameters);
            operations.push({
                groupName,
                helperName,
                method,
                operationId,
                pathParameters,
                queryParameters,
                hasRequiredQueryParameters: queryParameters.some((parameter) => parameter.required),
                requestBodyType: resolveRequestBodyType(operation.requestBody),
                ...resolveResponse(operation.responses),
                errorType: resolveErrorType(operation.responses),
                routePath: normalizeRoutePath(routePath),
            });
        }
    }

    return operations;
}

function groupOperations(operations) {
    const groupedOperations = new Map();
    for (const operation of operations) {
        const group = groupedOperations.get(operation.groupName) ?? new Map();
        if (group.has(operation.helperName)) {
            throw new Error(`Duplicate operationId '${operation.operationId}'.`);
        }

        group.set(operation.helperName, operation);
        groupedOperations.set(operation.groupName, group);
    }

    return groupedOperations;
}

function resolveParameters(routePath, pathParameters = [], operationParameters = []) {
    const pathParametersByName = new Map();
    const queryParameters = [];

    for (const parameter of [...pathParameters, ...operationParameters]) {
        if (!parameter?.name) {
            continue;
        }

        const resolvedParameter = {
            name: parameter.name,
            required: parameter.required === true,
            type: toTypeScriptType(parameter.schema),
        };

        if (parameter.in === "path") {
            pathParametersByName.set(parameter.name, resolvedParameter);
            continue;
        }

        if (parameter.in === "query") {
            queryParameters.push(resolvedParameter);
        }
    }

    const orderedPathParameters = [...routePath.matchAll(/\{([^}]+)\}/g)].map((match) => {
        const name = match[1];
        const parameter = pathParametersByName.get(name);
        if (!parameter) {
            throw new Error(`Path parameter '${name}' is missing OpenAPI metadata for '${routePath}'.`);
        }

        return parameter;
    });

    return {
        pathParameters: orderedPathParameters,
        queryParameters: queryParameters.sort((left, right) => left.name.localeCompare(right.name)),
    };
}

function resolveRequestBodyType(requestBody) {
    const schema = requestBody?.content?.["application/json"]?.schema;
    return schema ? toTypeScriptType(schema) : null;
}

function resolveResponse(responses = {}) {
    const successResponse = Object.entries(responses)
        .filter(([statusCode]) => /^2\d\d$/.test(statusCode))
        .sort(([left], [right]) => Number(left) - Number(right))[0]?.[1]
        ?? responses.default;

    const content = successResponse?.content ?? {};
    const jsonSchema = content["application/json"]?.schema;
    if (jsonSchema) {
        return {
            responseType: toTypeScriptType(jsonSchema),
            responseTypeOption: null,
        };
    }

    if (Object.keys(content).length > 0) {
        return {
            responseType: "Response",
            responseTypeOption: "response",
        };
    }

    return {
        responseType: "void",
        responseTypeOption: null,
    };
}

function resolveErrorType(responses = {}) {
    const errorTypes = [];

    for (const [statusCode, response] of Object.entries(responses)) {
        if (/^2\d\d$/.test(statusCode)) {
            continue;
        }

        const schema = response?.content?.["application/json"]?.schema;
        if (!schema) {
            continue;
        }

        const errorType = toTypeScriptType(schema);
        if (!errorTypes.includes(errorType)) {
            errorTypes.push(errorType);
        }
    }

    return errorTypes.length > 0 ? errorTypes.join(" | ") : "unknown";
}

function buildQueryParameterType(parameters) {
    const members = parameters.map((parameter) => `${parameter.name}${parameter.required ? "" : "?"}: ${parameter.type};`);
    return `{ ${members.join(" ")} }`;
}

function stripOpenApiTypesBanner(content) {
    return content.replace(/^\/\*\*[\s\S]*?\*\/\s*/u, "");
}

function normalizeOpenApiNumericTypes(value) {
    if (!value || typeof value !== "object") {
        return;
    }

    if (Array.isArray(value)) {
        for (const item of value) {
            normalizeOpenApiNumericTypes(item);
        }

        return;
    }

    if (Array.isArray(value.type) && (value.type.includes("integer") || value.type.includes("number"))) {
        value.type = value.type.filter((type) => type !== "string");
        delete value.pattern;
    }

    for (const item of Object.values(value)) {
        normalizeOpenApiNumericTypes(item);
    }
}

function isValidIdentifier(value) {
    return /^[A-Za-z_$][A-Za-z0-9_$]*$/u.test(value);
}

function run(command, args, cwd) {
    execFileSync(command, args, {
        cwd,
        stdio: "inherit",
    });
}
